import { mkdir, readFile, writeFile, cp, rm } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

// Render deployment artifacts without changing the production defaults or SDKs.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const project = process.argv[2];
if (!project || !/^[a-z][a-z0-9-]{4,28}[a-z0-9]$/.test(project)) {
  throw new Error("Usage: node infra/deploy/prepare.mjs PROJECT_ID");
}
const config = JSON.parse(
  await readFile(path.join(root, "infra/environments", project, "deployment.json"), "utf8"),
);
if (config.projectId !== project || config.firebase.projectId !== project) {
  throw new Error("Deployment and Firebase app project IDs must match");
}
if (typeof config.selfHosted !== "boolean")
  throw new Error("Specify selfHosted in deployment.json");
const firebase = path.join(root, "firebase");
const target = path.join(firebase, ".deploy", project);
await mkdir(target, { recursive: true });
await rm(path.join(target, "schema"), { recursive: true, force: true });
await cp(path.join(firebase, "dataconnect/schema"), path.join(target, "schema"), {
  recursive: true,
});
const connectors = [
  "teams",
  "billing",
  "logs",
  "builds",
  "secrets",
  "github",
  "webhooks",
  "dispatch",
];
for (const connector of connectors) {
  await rm(path.join(target, connector), { recursive: true, force: true });
  await cp(path.join(firebase, "dataconnect", connector), path.join(target, connector), {
    recursive: true,
  });
  // These are deployment copies; keep generated SDK configuration unchanged.
  await writeFile(path.join(target, connector, "connector.yaml"), `connectorId: ${connector}\n`);
}
await writeFile(
  path.join(target, "dataconnect.yaml"),
  JSON.stringify(
    {
      specVersion: "v1",
      serviceId: `${project}-service`,
      location: "asia-northeast1",
      schema: {
        source: "./schema",
        datasource: {
          postgresql: {
            database: `${project}-database`,
            schemaValidation: "COMPATIBLE",
            cloudSql: { instanceId: `${project}-instance` },
          },
        },
      },
      connectorDirs: connectors.map((name) => `./${name}`),
    },
    null,
    2,
  ) + "\n",
);
const base = JSON.parse(await readFile(path.join(firebase, "firebase.json"), "utf8"));
const dashboard = base.hosting.find((site) => site.public === "public");
if (!dashboard) throw new Error("Missing Dashboard Hosting configuration");
const deployment = {
  ...base,
  dataconnect: { source: `.deploy/${project}` },
  hosting: { ...dashboard, site: project },
};
// Never upload rendered deployment copies in the Functions source archive.
deployment.functions[0].ignore.push(".deploy", "firebase.*.local.json");
const output = path.join(firebase, `firebase.${project}.local.json`);
await writeFile(output, JSON.stringify(deployment, null, 2) + "\n");
await writeFile(
  path.join(target, "dashboard-defines.json"),
  JSON.stringify({ OPENCI_SELF_HOSTED: config.selfHosted }, null, 2) + "\n",
);

// This ignored file is generated per checkout, as in the regular Dashboard build.
// Native platforms have no app registration in a web-only deployment.
const values = Object.entries(config.firebase)
  .filter(([key]) =>
    ["apiKey", "appId", "messagingSenderId", "projectId", "authDomain", "storageBucket"].includes(
      key,
    ),
  )
  .map(([key, value]) => `    ${key}: ${JSON.stringify(value)},`)
  .join("\n");
await writeFile(
  path.join(root, "apps/dashboard/lib/firebase_options.dart"),
  `// Generated by infra/deploy/prepare.mjs for ${project}. Do not commit.\nimport 'package:firebase_core/firebase_core.dart';\n\nclass DefaultFirebaseOptions {\n  static const web = FirebaseOptions(\n${values}\n  );\n  static FirebaseOptions get ios => throw UnsupportedError('This deployment is web only');\n  static FirebaseOptions get android => throw UnsupportedError('This deployment is web only');\n  static FirebaseOptions get macos => throw UnsupportedError('This deployment is web only');\n}\n`,
);
console.log(`Prepared ${output}. Pass --project ${project} explicitly to Firebase CLI.`);
console.log(
  `Build Dashboard with --dart-define-from-file=${path.join(target, "dashboard-defines.json")}.`,
);
