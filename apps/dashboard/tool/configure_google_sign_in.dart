import 'dart:io';

// Firebase's generated options are injected by CI before a native build.
// Keep OAuth IDs and their callback schemes derived from that same config.
String googleSignInXcconfig(String options, String platform) {
  if (platform != 'ios' && platform != 'macos') {
    throw ArgumentError.value(platform, 'platform', 'Use ios or macos.');
  }
  final block = RegExp(
    'static const FirebaseOptions $platform = FirebaseOptions\\((.*?)\\);',
    dotAll: true,
  ).firstMatch(options)?.group(1);
  final clientId = block == null
      ? null
      : RegExp(
          r'''iosClientId:\s*['"]([^'"]+)['"]''',
        ).firstMatch(block)?.group(1);
  if (clientId == null ||
      !RegExp(
        r'^\d+-[a-zA-Z0-9]+\.apps\.googleusercontent\.com$',
      ).hasMatch(clientId)) {
    throw StateError(
      'Google sign-in is not configured for $platform. Enable the Google '
      'provider and regenerate lib/firebase_options.dart with FlutterFire.',
    );
  }
  final reversed = clientId.split('.').reversed.join('.');
  return '// Generated by tool/configure_google_sign_in.dart.\n'
      'OPENCI_GOOGLE_CLIENT_ID = $clientId\n'
      'OPENCI_GOOGLE_REVERSED_CLIENT_ID = $reversed\n';
}

void main(List<String> arguments) {
  if (arguments.length != 1) {
    throw ArgumentError(
      'Usage: dart run tool/configure_google_sign_in.dart ios|macos',
    );
  }
  final platform = arguments.single;
  final config = googleSignInXcconfig(
    File('lib/firebase_options.dart').readAsStringSync(),
    platform,
  );
  File('$platform/Flutter/GoogleSignIn.xcconfig').writeAsStringSync(config);
}
