import 'dart:convert';
import 'dart:math';

import 'package:mocktail/mocktail.dart';
import 'package:openci_server/github/generate_random_value.dart';
import 'package:test/test.dart';

class _MockRandom extends Mock implements Random {}

void main() {
  test('generates a 43-character URL-safe value from 32 bytes', () {
    final result = generateRandomValue();

    expect(result, matches(RegExp(r'^[A-Za-z0-9_-]{43}$')));
    expect(base64Url.decode(base64Url.normalize(result)), hasLength(32));
  });

  test('encodes the generated bytes as unpadded Base64url', () {
    // RFC 7636 Appendix B: example bytes and their encoded code verifier.
    const bytes = [
      116,
      24,
      223,
      180,
      151,
      153,
      224,
      37,
      79,
      250,
      96,
      125,
      216,
      173,
      187,
      186,
      22,
      212,
      37,
      77,
      105,
      214,
      191,
      240,
      91,
      88,
      5,
      88,
      83,
      132,
      141,
      121,
    ];
    final random = _MockRandom();
    var byteIndex = 0;
    when(() => random.nextInt(256)).thenAnswer((_) => bytes[byteIndex++]);

    final result = generateRandomValue(random: random);

    expect(result, 'dBjftJeZ4CVP-mB92K27uhbUJU1p1r_wW1gFWFOEjXk');
  });
}
